
console.log("----- DATE GET METHODS -----");

let today = new Date();

// Get methods
console.log("Year:", today.getFullYear());

console.log("Month:", today.getMonth());

console.log("Date:", today.getDate());

console.log("Day:", today.getDay());

console.log("Hours:", today.getHours());

console.log("Minutes:", today.getMinutes());

console.log("Seconds:", today.getSeconds());

console.log("Milliseconds:", today.getMilliseconds());

console.log("Timestamp:", today.getTime());

// UTC Get methods
console.log("UTC Year:", today.getUTCFullYear());

console.log("UTC Month:", today.getUTCMonth());

console.log("UTC Date:", today.getUTCDate());

console.log("UTC Day:", today.getUTCDay());

console.log("UTC Hours:", today.getUTCHours());

console.log("UTC Minutes:", today.getUTCMinutes());

console.log("UTC Seconds:", today.getUTCSeconds());

console.log("UTC Milliseconds:", today.getUTCMilliseconds());
